export function t(key: string, lang?: Language): string {
  const currentLang = lang || getLanguage();
  return translations[currentLang]?.[key] || translations.en[key] || key;
}

// Hook for reactive translations
import { useState, useEffect, useCallback } from "react";

export function useTranslation() {
  const [lang, setLang] = useState<Language>(getLanguage);

  useEffect(() => {
    const handler = (e: Event) => {
      setLang((e as CustomEvent).detail as Language);
    };
    window.addEventListener("language-changed", handler);
    return () => window.removeEventListener("language-changed", handler);
  }, []);

  const translate = useCallback((key: string) => t(key, lang), [lang]);

  return { t: translate, lang, setLang: setLanguage };
}
